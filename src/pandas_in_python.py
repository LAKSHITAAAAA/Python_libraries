# Merging and Joining
# 1. Merging : combining 2 or more dataframes'
# rows together based on a common key column
# syntax : pd.merge(df1,df2, on= "Column_name",how="type of join")
# df1 and df2 where data is already stored.
# on=" Column_name" the column common in both dataframes.
# how: what type of join to be applied here.

import pandas as pd
# customer dataframe
df_customer=pd.DataFrame({
    'CustomerID': [1,2,3,4],
    'Name': ['Lakshita','Shruti','Akshaya','Aditya']
})
# orders dataframe
df_orders=pd.DataFrame({
    'CustomerID': [1,2,3,5],
    'OrderAmt': [200,250,380,460]

    })
# merge
# inner join
df_merged=pd.merge(df_customer,df_orders,on="CustomerID",how="inner")
print("Inner Join")
print(df_merged)
#outer join
df_merged=pd.merge(df_customer,df_orders,on="CustomerID",how="outer")
print(' ')
print("Outer Join")
