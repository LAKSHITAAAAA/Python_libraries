# Concatenating Dataframes.
"""Combining dataframes horizontally(column-wise) or vertically(row-wise)"""
""" Syntax: pd.concate([df1,df2],axis=0/1,ignore_index=True)
[df1,df2]: A list of dataframe that needs to be concatenated with each other
axis=0/1: axis=0 for row and axis=1 for column
ignore_index=True: ignoring the original index of the two dataframes and
having one universal index for the merged dataframe.
"""
# Vertically
import pandas as pd
#region1
df_Region1=pd.DataFrame({
    'CustomerID': [1,2,3,4],
    'Name': ['Lakshita','Shruti','Akshaya','Aditya']
})
